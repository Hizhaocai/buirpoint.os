function runSupabase(args, options = {}) {
  const command = process.platform === "win32"
    ? resolve(projectRoot, "node_modules", ".bin", "supabase.cmd")
    : "supabase";
  return execFileSync(command, args, {
    cwd: projectRoot,
    encoding: "utf8",
    stdio: options.capture ? ["ignore", "pipe", "inherit"] : "inherit",
    shell: process.platform === "win32",
  });
}

function readStatusEnv() {
  const output = runSupabase(["status", "-o", "env"], { capture: true });
  const values = Object.fromEntries(
    output
      .split(/\r?\n/)
      .filter((line) => line.includes("="))
      .map((line) => {
        const index = line.indexOf("=");
        const value = line.slice(index + 1).trim();
        return [
          line.slice(0, index).trim(),
          value.startsWith('"') && value.endsWith('"') ? value.slice(1, -1) : value,
        ];
      }),
  );

  if (!values.API_URL || !values.ANON_KEY || !values.SERVICE_ROLE_KEY) {
    throw new Error("Supabase local status did not provide API_URL, ANON_KEY, and SERVICE_ROLE_KEY.");
  }
  if (!/^http:\/\/(127\.0\.0\.1|localhost)(?::\d+)?$/i.test(values.API_URL)) {
    throw new Error("Refusing to initialize users against a non-local Supabase API.");
  }
  return values;
}

async function apiRequest(url, serviceRoleKey, path, options = {}) {
  const response = await fetch(`${url}${path}`, {
    ...options,
    headers: {
      apikey: serviceRoleKey,
      Authorization: `Bearer ${serviceRoleKey}`,
      "Content-Type": "application/json",
      ...(options.headers ?? {}),
    },
  });
  if (!response.ok) {
    throw new Error(`Local Supabase request failed: ${response.status} ${await response.text()}`);
  }
  return response.status === 204 ? null : response.json();
}

function delay(milliseconds) {
  return new Promise((resolveDelay) => setTimeout(resolveDelay, milliseconds));
}

async function waitForLocalAuth(config) {
  let lastStatus = "unreachable";

  for (let attempt = 0; attempt < 45; attempt += 1) {
    try {
      const response = await fetch(`${config.API_URL}/auth/v1/health`, {
        headers: { apikey: config.ANON_KEY },
      });
      if (response.ok) return;
      lastStatus = String(response.status);
    } catch {
      lastStatus = "unreachable";
    }
    await delay(1000);
  }

  throw new Error(`Local Supabase Auth was not ready after 45 seconds (last status: ${lastStatus}).`);
}

async function ensureUser(config, user) {
  const list = await apiRequest(config.API_URL, config.SERVICE_ROLE_KEY, "/auth/v1/admin/users?page=1&per_page=1000");
  const existing = list.users.find((candidate) => candidate.email === user.email);
  const endpoint = existing ? `/auth/v1/admin/users/${existing.id}` : "/auth/v1/admin/users";
  const method = existing ? "PUT" : "POST";
  const result = await apiRequest(config.API_URL, config.SERVICE_ROLE_KEY, endpoint, {
    method,
    body: JSON.stringify({
      email: user.email,
      password,
      email_confirm: true,
      user_metadata: { name: user.name },
    }),
  });
  const id = existing?.id ?? result.id ?? result.user?.id;
  if (!id) {
    throw new Error(`Local Auth did not return an id for ${user.email}.`);
  }

  await apiRequest(config.API_URL, config.SERVICE_ROLE_KEY, `/rest/v1/profiles?id=eq.${id}`, {
    method: "PATCH",
    headers: { Prefer: "return=minimal" },
    body: JSON.stringify({ name: user.name, role: user.role, status: "active" }),
  });
  return { ...user, id };
}

async function verifyUser(config, user) {
  const tokenResponse = await fetch(`${config.API_URL}/auth/v1/token?grant_type=password`, {
    method: "POST",
    headers: { apikey: config.ANON_KEY, "Content-Type": "application/json" },
    body: JSON.stringify({ email: user.email, password }),
  });
  if (!tokenResponse.ok) throw new Error(`Login verification failed for ${user.email}.`);
  const { access_token: accessToken } = await tokenResponse.json();
  const profileResponse = await fetch(`${config.API_URL}/rest/v1/profiles?select=role,status&id=eq.${user.id}`, {
    headers: { apikey: config.ANON_KEY, Authorization: `Bearer ${accessToken}` },
  });
  const profiles = await profileResponse.json();
  if (!profileResponse.ok || profiles.length !== 1 || profiles[0].role !== user.role || profiles[0].status !== "active") {
    throw new Error(`Profile and RLS verification failed for ${user.email}.`);
  }
  return accessToken;
}

