async function verifyOrderRls(config, accessToken, expectedCount) {
  const response = await fetch(`${config.API_URL}/rest/v1/orders?select=id`, {
    headers: { apikey: config.ANON_KEY, Authorization: `Bearer ${accessToken}` },
  });
  const orders = await response.json();
  if (!response.ok || orders.length !== expectedCount) {
    throw new Error(`Order RLS verification failed (expected ${expectedCount}, received ${orders.length}).`);
  }
}

